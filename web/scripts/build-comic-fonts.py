"""Build unicode-range sliced woff2 files for the KT Comic theme fonts.

Reproducible: same source fonts + glyph lists -> byte-identical output.

    pip install 'fonttools[woff]==4.*' brotli
    python3 scripts/build-comic-fonts.py \
        --display /path/SmileySans-Oblique.ttf \
        --body /path/ZCOOLKuaiLe-Regular.ttf

Sources (SIL OFL 1.1):
  * Smiley Sans Oblique v2.0.1 (atelier-anchor/smiley-sans). Its Reserved
    Font Names "Smiley"/"得意黑" forbid reuse in a Modified Version, so the
    name table is rewritten to "KTHome Display".
  * ZCOOL KuaiLe Regular (google/fonts ofl/zcoolkuaile), served as
    "KTHome KuaiLe".

Slicing:
  slice 000  ASCII, Latin-1, common punctuation and every glyph in
             src/assets/comic/fonts/glyphs*.txt (home/auth/console copy).
             Preloaded by index.html when KT Comic is active.
  next       GB2312 level-1 hanzi (≈ the 3,755 most common characters), in
             GB2312 order, CHUNK_COMMON glyphs per slice.
  rest       everything else in the font, by code point, CHUNK_REST per slice.

Writes public/fonts/kt-comic/<family>/<nn>-<hash>.woff2 and
src/styles/comic/comic-fonts-sliced.css (generated, do not edit), and
updates the preload list in index.html (between the kt-comic-preload markers).
"""

import argparse
import hashlib
import io
import os
import re
import shutil

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, 'public', 'fonts', 'kt-comic')
CSS_OUT = os.path.join(ROOT, 'src', 'styles', 'comic', 'comic-fonts-sliced.css')
GLYPH_FILES = [
    os.path.join(ROOT, 'src', 'assets', 'comic', 'fonts', n)
    for n in ('glyphs.txt', 'glyphs-console.txt')
]
CHUNK_COMMON = 120
CHUNK_REST = 200

BASE_RANGES = [
    (0x20, 0x7E), (0xA0, 0xFF), (0x2010, 0x2027), (0x2030, 0x203A),
    (0x3000, 0x303F), (0xFF00, 0xFFEF),
]

FAMILIES = [
    # (cli arg, css family, dir, rename-to or None)
    ('display', 'KTHome Display', 'display', 'KTHome Display'),
    ('body', 'KTHome KuaiLe', 'kuaile', None),
]


def gb2312_level1():
    out = []
    for hi in range(0xB0, 0xD8):
        for lo in range(0xA1, 0xFF):
            try:
                out.append(ord(bytes([hi, lo]).decode('gb2312')))
            except UnicodeDecodeError:
                pass
    return out


def plan_slices(cmap):
    have = set(cmap)
    base = set()
    for a, b in BASE_RANGES:
        base.update(range(a, b + 1))
    for path in GLYPH_FILES:
        with open(path, encoding='utf-8') as f:
            base.update(ord(c) for c in f.read() if not c.isspace())
    slices = [sorted(base & have)]
    used = set(slices[0])
    common = [c for c in gb2312_level1() if c in have and c not in used]
    for i in range(0, len(common), CHUNK_COMMON):
        slices.append(sorted(common[i:i + CHUNK_COMMON]))
    used.update(common)
    rest = sorted(have - used - {0})
    for i in range(0, len(rest), CHUNK_REST):
        slices.append(rest[i:i + CHUNK_REST])
    return slices


def rename(font, family):
    ps = family.replace(' ', '') + '-Regular'
    for rec in font['name'].names:
        if rec.nameID in (1, 16, 21):
            rec.string = family
        elif rec.nameID in (2, 17, 22):
            rec.string = 'Regular'
        elif rec.nameID == 3:
            rec.string = ps + ';kt-api'
        elif rec.nameID == 4:
            rec.string = family
        elif rec.nameID == 6:
            rec.string = ps


def unicode_range(cps):
    parts, start, prev = [], None, None
    for c in cps:
        if start is None:
            start = prev = c
        elif c == prev + 1:
            prev = c
        else:
            parts.append((start, prev))
            start = prev = c
    if start is not None:
        parts.append((start, prev))
    return ', '.join(
        f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in parts
    )


def build_slice(src, cps, rename_to):
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['*']
    opts.hinting = False
    opts.desubroutinize = True
    opts.name_IDs = ['*']
    opts.name_languages = ['*']
    font = TTFont(src, recalcTimestamp=False)
    font['head'].modified = font['head'].created
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=cps)
    sub.subset(font)
    if rename_to:
        rename(font, rename_to)
    buf = io.BytesIO()
    font.flavor = 'woff2'
    font.save(buf, reorderTables=True)
    return buf.getvalue()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--display', required=True)
    ap.add_argument('--body', required=True)
    args = ap.parse_args()

    if os.path.isdir(OUT_DIR):
        shutil.rmtree(OUT_DIR)
    css = [
        '/* GENERATED by scripts/build-comic-fonts.py — do not edit. */',
        '/* Unicode-range slices: browsers fetch only slices whose',
        '   characters are rendered in that family. */',
    ]
    preload = []
    for arg, family, sub_dir, rename_to in FAMILIES:
        src = getattr(args, arg)
        cmap = TTFont(src).getBestCmap()
        slices = plan_slices(cmap)
        os.makedirs(os.path.join(OUT_DIR, sub_dir), exist_ok=True)
        total = 0
        for idx, cps in enumerate(slices):
            data = build_slice(src, cps, rename_to)
            digest = hashlib.sha256(data).hexdigest()[:8]
            name = f'{idx:03d}-{digest}.woff2'
            with open(os.path.join(OUT_DIR, sub_dir, name), 'wb') as f:
                f.write(data)
            total += len(data)
            url = f'/fonts/kt-comic/{sub_dir}/{name}'
            if idx == 0:
                preload.append(url)
            css.append(
                '@font-face {\n'
                f"  font-family: '{family}';\n"
                f"  src: url('{url}') format('woff2');\n"
                '  font-display: swap;\n'
                f'  unicode-range: {unicode_range(cps)};\n'
                '}'
            )
        print(f'{family}: {len(slices)} slices, {total} bytes')
    with open(CSS_OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(css) + '\n')
    with open(os.path.join(OUT_DIR, 'preload.txt'), 'w') as f:
        f.write('\n'.join(preload) + '\n')
    html_path = os.path.join(ROOT, 'index.html')
    with open(html_path, encoding='utf-8') as f:
        html = f.read()
    listed = ', '.join(f"'{u}'" for u in preload)
    html, n = re.subn(
        r'/\*kt-comic-preload\*/.*?/\*end\*/',
        lambda _m: f'/*kt-comic-preload*/{listed}/*end*/',
        html,
    )
    if n != 1:
        raise SystemExit('index.html kt-comic-preload marker not found')
    with open(html_path, 'w', encoding='utf-8') as f:
        f.write(html)
    print('preload:', *preload)


if __name__ == '__main__':
    main()
