/*
 * Regenerates src/lib/lobe-icon-variants.gen.ts from @lobehub/icons/es/toc.json.
 * The full toc (~100KB) is only needed for its per-icon variant flags, so the
 * app ships this compact bitmask table instead. Run after upgrading the icons
 * package: `bun run icons:variants`. A unit test fails when it is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const toc = JSON.parse(
  readFileSync(resolve(root, 'node_modules/@lobehub/icons/es/toc.json'), 'utf8')
)
const FLAGS = [
  'hasAvatar',
  'hasBrand',
  'hasBrandColor',
  'hasColor',
  'hasCombine',
  'hasText',
  'hasTextCn',
  'hasTextColor',
]
const header = readFileSync(resolve(root, 'src/lib/lobe-icon.tsx'), 'utf8')
  .split('*/')[0]
  .concat('*/\n')
const entries = toc
  .map((icon) => {
    let mask = 0
    FLAGS.forEach((flag, i) => {
      if (icon.param?.[flag]) mask |= 1 << i
    })
    return `  ${JSON.stringify(icon.id)}: ${mask},`
  })
  .join('\n')
const out = `${header}// Generated by scripts/gen-lobe-icon-variants.mjs. Do not edit.
// Bit i set => the icon has variant flag LOBE_ICON_FLAGS[i].

export const LOBE_ICON_FLAGS = ${JSON.stringify(FLAGS)} as const

export const LOBE_ICON_VARIANT_MASKS: Record<string, number> = {
${entries}
}
`
writeFileSync(resolve(root, 'src/lib/lobe-icon-variants.gen.ts'), out)
console.log(`wrote ${toc.length} icons`)
